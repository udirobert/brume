// Generates `mcp/widget-bundle.js` from `mcp/widget.js` so the Cloudflare
// Worker (`mcp/worker.js`) can import the self-contained widget HTML without
// calling `node:fs` at request time.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { buildWidgetHtml } from "../widget.js";

const outPath = path.resolve(
  fileURLToPath(new URL(".", import.meta.url)),
  "../widget-bundle.js",
);

const html = buildWidgetHtml();
const content = `// Generated by scripts/build-worker.mjs — do not edit by hand.\nexport const WIDGET_HTML = ${JSON.stringify(html)};\n`;

writeFileSync(outPath, content, "utf8");
console.log(`Wrote ${outPath} (${html.length} bytes)`);
